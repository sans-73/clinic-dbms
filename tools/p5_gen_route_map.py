"""Writes docs/phase5/ROUTE_MAP.md: every URL, method, allowed role(s), and the data-layer functions behind it.
    python tools/p5_gen_route_map.py"""
from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = []
for f in sorted((ROOT / "app" / "routes").glob("*.py")):
    if f.name == "__init__.py":
        continue
    src = f.read_text(encoding="utf-8")
    tree = ast.parse(src)
    prefix = (re.search(r'APIRouter\([^)]*prefix="([^"]*)"', src) or [None, ""])[1]
    guards = {}
    for n in tree.body:
        if isinstance(n, ast.Assign) and isinstance(n.value, ast.Call) and getattr(n.value.func, "attr", "") == "require":
            guards[n.targets[0].id] = [a.value for a in n.value.args if isinstance(a, ast.Constant)] or ["any logged-in"]
    for n in tree.body:
        if not isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for d in n.decorator_list:
            if isinstance(d, ast.Call) and getattr(d.func, "attr", "") in ("get", "post") and d.args:
                path = prefix + d.args[0].value
                role = "public"
                for dflt in n.args.defaults + n.args.kw_defaults:
                    if isinstance(dflt, ast.Call) and getattr(dflt.func, "id", "") == "Depends" and dflt.args:
                        a0 = dflt.args[0]
                        if isinstance(a0, ast.Name) and a0.id in guards:
                            role = ", ".join(guards[a0.id])
                        elif isinstance(a0, ast.Call) and getattr(a0.func, "attr", "") == "require":
                            role = ", ".join(x.value for x in a0.args if isinstance(x, ast.Constant)) or "any logged-in"
                calls = sorted({f"{x.value.id}.{x.attr}" for x in ast.walk(n) if isinstance(x, ast.Attribute) and isinstance(x.value, ast.Name)
                                and x.value.id in ("P", "C", "PH", "N", "B", "O", "F")})
                rows.append((f.stem, d.func.attr.upper(), path, role, ", ".join(calls)))
out = ["# Route map (generated)", "", "Generated by `tools/p5_gen_route_map.py`. Role = ACTIVE hat required. 'public' = no login (family link).", "",
       "| Module | Method | URL | Role(s) | Data-layer functions |", "|---|---|---|---|---|"]
out += [f"| {m} | {me} | `{u}` | {r} | {c} |" for m, me, u, r, c in rows]
p = ROOT / "docs" / "phase5" / "ROUTE_MAP.md"
p.write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", p, len(rows), "routes")
