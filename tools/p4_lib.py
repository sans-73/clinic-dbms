"""p4_lib.py - shared helpers for ALL Phase-4 tools (seed, bulk generator, benchmarks).

WHY THIS FILE EXISTS
  The real schema (104 tables) was generated by another AI from tools/schema_spec.py.
  Phase-4 code was written against the ER model (docs/design/01_er_model.md) and was NOT
  run against that exact schema. This loader is therefore SCHEMA-AWARE: it reads
  information_schema, auto-fixes enum spellings, fills standard event columns, fills any
  other NOT NULL column with a harmless default, and REPORTS every difference
  (unknown columns, auto-filled columns, enum fixes). Run any tool with --check first.

Install:  pip install pymysql cryptography matplotlib
"""
from __future__ import annotations

import contextlib
import difflib
import os
import re
import subprocess
import sys
import uuid
from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ESC_COLS = ("occurred_at", "recorded_at", "recorded_by", "recorded_by_role", "is_backfilled", "request_uuid")


def utcnow() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0)


def load_env() -> dict:
    env: dict = {}
    p = ROOT / ".env"
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip().strip('"').strip("'")
    return env


def connect(db: str | None):
    """Connect to the docker MySQL (host port 3307, see docker-compose.yml)."""
    try:
        import pymysql
    except ImportError:
        sys.exit("Missing package. Run:  pip install pymysql cryptography matplotlib")
    env = load_env()
    return pymysql.connect(
        host=os.getenv("MYSQL_HOST", "127.0.0.1"),
        port=int(os.getenv("MYSQL_PORT", "3307")),
        user=os.getenv("MYSQL_USER", "root"),
        password=os.getenv("MYSQL_ROOT_PASSWORD", env.get("MYSQL_ROOT_PASSWORD", "")),
        database=db, charset="utf8mb4", autocommit=False,
    )


def run_sql_text(sql: str, db: str | None = None) -> str:
    """Pipe SQL text into the mysql CLI inside the container (handles DELIMITER, big files)."""
    inner = 'mysql -uroot -p"$MYSQL_ROOT_PASSWORD" ' + (db or "")
    r = subprocess.run(["docker", "compose", "exec", "-T", "mysql", "sh", "-c", inner],
                       input=sql.encode("utf-8"), cwd=ROOT, capture_output=True)
    out = (r.stdout + r.stderr).decode("utf-8", "replace")
    if r.returncode != 0 or re.search(r"^ERROR", out, re.M):
        raise RuntimeError(out)
    return out


# ----------------------------------------------------------------------------- schema
@dataclass
class Col:
    name: str
    data_type: str
    column_type: str
    nullable: bool
    default: object
    extra: str
    maxlen: int | None

    @property
    def generated(self) -> bool:
        return bool(re.search(r"(VIRTUAL|STORED) GENERATED", self.extra or "", re.I))

    @property
    def auto(self) -> bool:
        return "auto_increment" in (self.extra or "").lower()

    @property
    def enum_values(self) -> list[str]:
        m = re.match(r"enum\((.*)\)$", self.column_type or "", re.I)
        return re.findall(r"'((?:[^']|'')*)'", m.group(1)) if m else []


class Schema:
    def __init__(self, rows):
        self.tables: dict[str, dict[str, Col]] = {}
        for t, c, dt, ct, nl, df, ex, ml in rows:
            self.tables.setdefault(t, {})[c] = Col(c, dt, ct, nl == "YES", df, ex or "", ml)

    @classmethod
    def from_db(cls, conn, db: str) -> "Schema":
        cur = conn.cursor()
        cur.execute("SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA, "
                    "CHARACTER_MAXIMUM_LENGTH FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s "
                    "ORDER BY TABLE_NAME, ORDINAL_POSITION", (db,))
        return cls(cur.fetchall())

    def cols(self, table: str) -> dict[str, Col]:
        return self.tables.get(table, {})


class SchemaMismatch(Exception):
    pass


class LoadError(Exception):
    pass


@dataclass
class Actor:
    staff_id: int
    role: str          # role_code, e.g. 'OWNER' (this is what @app_role holds)


def _key(s: str) -> str:
    return re.sub(r"[\s_\-]+", "", s.lower())


class Loader:
    """Schema-aware row inserter. See module docstring."""

    def __init__(self, conn, db: str, lenient: bool = False, esc: bool = True, schema: Schema | None = None):
        self.conn, self.db, self.lenient, self.esc = conn, db, lenient, esc
        self.schema = schema or Schema.from_db(conn, db)
        self.cur = conn.cursor()
        self.cur.execute("SET time_zone='+00:00'")
        self.actor: Actor | None = None
        self._roles: dict[str, int] | None = None
        self.report: dict[str, set] = defaultdict(set)
        self.failures: list[tuple[str, str]] = []
        self.counts: dict[str, int] = defaultdict(int)

    # ---- actors
    def role_id(self, code: str) -> int | None:
        if self._roles is None:
            self.cur.execute("SELECT role_code, role_id FROM role")
            self._roles = {c: i for c, i in self.cur.fetchall()}
        return self._roles.get(code)

    def refresh_roles(self):
        self._roles = None

    def act(self, actor: Actor | None):
        """Set the G5 session variables (what the web app does on every connection)."""
        self.actor = actor
        if actor:
            self.cur.execute("SET @app_user_id=%s, @app_role=%s", (actor.staff_id, actor.role))

    # ---- value helpers
    def _enum_fix(self, table: str, col: Col, value):
        ev = col.enum_values
        if not ev or not isinstance(value, str) or value in ev:
            return value
        km = {_key(e): e for e in ev}
        if _key(value) in km:
            fixed = km[_key(value)]
        else:
            fixed = next((e for e in ev if _key(e).startswith(_key(value)) or _key(value).startswith(_key(e))), None)
        if fixed is None:
            self.report["enum_unmatched"].add(f"{table}.{col.name}: '{value}' not in {ev}")
            return value
        self.report["enum_fixed"].add(f"{table}.{col.name}: '{value}' -> '{fixed}'")
        return fixed

    def pick(self, table: str, col: str, preferred: list[str]):
        """Choose the first preferred value that the enum allows (or the first preferred)."""
        c = self.schema.cols(table).get(col)
        ev = c.enum_values if c else []
        for p in preferred:
            if not ev or p in ev or _key(p) in {_key(e) for e in ev}:
                return self._enum_fix(table, c, p) if c else p
        return ev[0] if ev else preferred[0]

    def generic(self, table: str, c: Col):
        dt = c.data_type.lower()
        if c.name == "created_by" and self.actor:
            return self.actor.staff_id
        if dt == "enum":
            return c.enum_values[0]
        if dt in ("int", "bigint", "smallint", "mediumint", "tinyint", "decimal", "numeric", "float", "double", "year"):
            return 0
        if dt == "date":
            return utcnow().date()
        if dt in ("datetime", "timestamp"):
            return utcnow()
        if dt == "time":
            return "00:00:00"
        if dt == "json":
            return "{}"
        if dt in ("char", "varchar", "text", "tinytext", "mediumtext", "longtext"):
            return "n/a"[: c.maxlen] if c.maxlen else "n/a"
        if dt in ("blob", "tinyblob", "mediumblob", "longblob", "binary", "varbinary"):
            return b"\x00"
        return None

    def esc_values(self, table: str, occurred: datetime | None = None, actor: Actor | None = None) -> dict:
        """Standard event columns for `table` (only those that exist)."""
        info = self.schema.cols(table)
        actor = actor or self.actor
        if "recorded_by" not in info:
            return {}
        if actor is None:
            raise SchemaMismatch(f"{table}: no actor set (call L.act(Actor(...)) first)")
        now = utcnow()
        occ = occurred or now
        out: dict = {}
        if "occurred_at" in info:
            out["occurred_at"] = occ
        if "recorded_at" in info:
            out["recorded_at"] = occ if occ < now else now
        out["recorded_by"] = actor.staff_id
        if "recorded_by_role" in info:
            rc = info["recorded_by_role"]
            out["recorded_by_role"] = (actor.role if rc.data_type in ("varchar", "char", "enum")
                                       else (self.role_id(actor.role) or 0))
        if "is_backfilled" in info:
            out["is_backfilled"] = 1 if (now - occ).total_seconds() > 600 else 0
        if "request_uuid" in info:
            u = uuid.uuid4()
            out["request_uuid"] = u.bytes if info["request_uuid"].data_type in ("binary", "varbinary") else str(u)
        return out

    def prepare(self, table: str, row: dict) -> dict:
        info = self.schema.cols(table)
        if not info:
            raise SchemaMismatch(f"table `{table}` does not exist in {self.db}")
        data: dict = {}
        for k, v in row.items():
            if k not in info:
                close = difflib.get_close_matches(k, list(info), n=2)
                self.report["unknown_columns"].add(f"{table}.{k}  (did you mean: {', '.join(close) or '?'})")
                if not self.lenient:
                    raise SchemaMismatch(f"{table}.{k} does not exist. Close: {close}. Columns: {list(info)}")
                continue
            data[k] = self._enum_fix(table, info[k], v)
        if self.esc:
            occ = data.get("occurred_at")
            for k, v in self.esc_values(table, occ).items():
                data.setdefault(k, v)
        for name, c in info.items():
            if name in data or c.auto or c.generated or c.nullable or c.default is not None:
                continue
            data[name] = self.generic(table, c)
            self.report["auto_filled"].add(f"{table}.{name}")
        return data

    # ---- writes
    def insert(self, table: str, row: dict, actor: Actor | None = None) -> int:
        if actor:
            self.act(actor)
        data = self.prepare(table, row)
        cols = list(data)
        sql = f"INSERT INTO `{table}` ({','.join('`' + c + '`' for c in cols)}) VALUES ({','.join(['%s'] * len(cols))})"
        try:
            self.cur.execute(sql, [data[c] for c in cols])
        except Exception as e:                     # add context, keep original type name
            raise LoadError(f"[{table}] {type(e).__name__}: {e}  | row={ {k: data[k] for k in list(data)[:12]} }") from e
        self.counts[table] += 1
        return self.cur.lastrowid

    def call(self, proc: str, *args, outs: int = 0, actor: Actor | None = None):
        if actor:
            self.act(actor)
        ph = ",".join(["%s"] * len(args) + [f"@o{i}" for i in range(outs)])
        try:
            self.cur.execute(f"CALL {proc}({ph})", args)
            while self.cur.nextset():
                pass
            if outs:
                self.cur.execute("SELECT " + ",".join(f"@o{i}" for i in range(outs)))
                r = self.cur.fetchone()
                return r[0] if outs == 1 else r
        except Exception as e:
            raise LoadError(f"[CALL {proc}{args}] {type(e).__name__}: {e}") from e

    def one(self, sql: str, args=()):
        self.cur.execute(sql, args)
        r = self.cur.fetchone()
        return r[0] if r else None

    def bulk(self, table: str, cols: list[str], rows, batch: int = 5000, label: str | None = None) -> int:
        """Fast path: caller supplies ALL needed columns (incl. event columns). Constant defaults
        are appended for other NOT NULL columns. Rows = iterable of tuples."""
        info = self.schema.cols(table)
        if not info:
            raise SchemaMismatch(f"table `{table}` does not exist")
        bad = [c for c in cols if c not in info]
        if bad:
            raise SchemaMismatch(f"{table}: unknown columns {bad}. Columns: {list(info)}")
        const = {}
        for n, c in info.items():
            if n in cols or c.auto or c.generated or c.nullable or c.default is not None:
                continue
            const[n] = self.generic(table, c)
            self.report["auto_filled"].add(f"{table}.{n}")
        allc = list(cols) + list(const)
        tail = tuple(const.values())
        sql = f"INSERT INTO `{table}` ({','.join('`' + c + '`' for c in allc)}) VALUES ({','.join(['%s'] * len(allc))})"
        buf, total = [], 0
        for r in rows:
            buf.append(tuple(r) + tail)
            if len(buf) >= batch:
                self._flush(sql, buf, table)
                total += len(buf)
                buf = []
                if total % (batch * 20) == 0:
                    self.conn.commit()
                    print(f"    {label or table}: {total:,} rows...", flush=True)
        if buf:
            self._flush(sql, buf, table)
            total += len(buf)
        self.conn.commit()
        self.counts[table] += total
        print(f"  {label or table}: {total:,} rows", flush=True)
        return total

    def _flush(self, sql, buf, table):
        try:
            self.cur.executemany(sql, buf)
        except Exception as e:
            raise LoadError(f"[{table}] bulk insert failed: {type(e).__name__}: {e} | first row={buf[0]}") from e

    # ---- isolation of independent stories
    @contextlib.contextmanager
    def unit(self, name: str, critical: bool = False):
        sp = "sp_" + re.sub(r"\W", "_", name)[:40]
        self.cur.execute(f"SAVEPOINT {sp}")
        try:
            yield
        except Exception as e:
            with contextlib.suppress(Exception):
                self.cur.execute(f"ROLLBACK TO SAVEPOINT {sp}")
            self.failures.append((name, str(e)[:700]))
            print(f"  !! unit '{name}' FAILED: {str(e)[:300]}")
            if critical:
                raise
        else:
            with contextlib.suppress(Exception):
                self.cur.execute(f"RELEASE SAVEPOINT {sp}")

    def print_report(self):
        print("\n================ LOADER REPORT ================")
        print("rows inserted:", dict(self.counts))
        titles = {"unknown_columns": "COLUMNS I ASSUMED BUT SCHEMA LACKS (fix names in code)",
                  "enum_unmatched": "ENUM VALUES THAT DO NOT EXIST (fix values in code)",
                  "enum_fixed": "enum spellings auto-fixed (informational)",
                  "auto_filled": "NOT NULL columns auto-filled with defaults (check meaning!)"}
        for k, t in titles.items():
            if self.report[k]:
                print(f"\n-- {t}:")
                for x in sorted(self.report[k]):
                    print("   ", x)
        if self.failures:
            print("\n-- FAILED UNITS (each rolled back alone; send these lines to the DB agent):")
            for n, m in self.failures:
                print(f"   * {n}: {m}")
        else:
            print("\nNo failed units.")
