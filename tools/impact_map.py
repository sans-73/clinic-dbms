#!/usr/bin/env python3
"""Impact map: which procedures / functions / views / trigger snippets / tests touch which table.
  python tools/impact_map.py                -> rewrites docs/pooling/IMPACT_MAP.md (all tables)
  python tools/impact_map.py patient_phone  -> prints everything that must be reviewed when that table (or column) changes
Use it whenever P1-3 / P1-4 (or a reviewer) changes the design: the list below is your to-do for that change."""
import os, re, sys, glob, collections
sys.path.insert(0, os.path.dirname(__file__))
import schema_spec as S
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
tables = [t['name'] for t in S.T]


def blocks():
    out = []
    files = sorted(glob.glob(os.path.join(ROOT, 'db/logic/0[2-9]*.sql'))) + [os.path.join(ROOT, 'tools/sql_src/01_foundation_head.sql')]
    for f in files:
        t = open(f, encoding='utf-8').read(); rel = os.path.relpath(f, ROOT)
        starts = [(m.start(), m.group(1).upper(), m.group(2)) for m in re.finditer(r'CREATE\s+(?:OR\s+REPLACE\s+)?(PROCEDURE|FUNCTION|VIEW)\s+`?(\w+)`?', t)]
        for i, (pos, kind, name) in enumerate(starts):
            end = starts[i + 1][0] if i + 1 < len(starts) else len(t)
            out.append((rel, kind, name, re.sub(r'--[^\n]*', '', t[pos:end])))
    return out


def build():
    refs = collections.defaultdict(lambda: collections.defaultdict(set))
    for rel, kind, name, body in blocks():
        for tb in tables:
            if re.search(r'(?<![\w])' + tb + r'(?![\w])', body):
                refs[tb][kind.lower()].add(f'{name} ({os.path.basename(rel)})')
    for t in S.T:
        snip = t['bi'] + ' ' + t['bu']
        for tb in tables:
            if tb != t['name'] and re.search(r'(?<![\w])' + tb + r'(?![\w])', snip):
                refs[tb]['trigger'].add(f"trg_{t['name']}")
    tests = open(os.path.join(ROOT, 'db/tests/rule_tests.sql')).read() if os.path.exists(os.path.join(ROOT, 'db/tests/rule_tests.sql')) else ''
    return refs, {tb: len(re.findall(r'(?<![\w])' + tb + r'(?![\w])', tests)) for tb in tables}


def fmt(tb, refs, tcount):
    r = refs.get(tb, {})
    lines = [f'### `{tb}`', f"- spec: `tools/schema_spec.py` (table), rules: {next(t['rules'] for t in S.T if t['name'] == tb) or '-'}"]
    for k, label in (('procedure', 'procedures'), ('function', 'functions'), ('view', 'views'), ('trigger', 'triggers that read it')):
        if r.get(k): lines.append(f"- {label}: " + ', '.join(sorted(r[k])))
    lines.append(f'- mentioned in rule tests: {tcount.get(tb, 0)} times')
    return lines


if __name__ == '__main__':
    refs, tc = build()
    if len(sys.argv) > 1:
        for tb in sys.argv[1:]:
            if tb not in tables: sys.exit(f'unknown table {tb}')
            print('\n'.join(fmt(tb, refs, tc)))
    else:
        md = ['# Impact map (generated by tools/impact_map.py)', '', 'When a table or column changes, review everything listed under that table, then run `python tools/build_db.py`, `python tools/verify_kit.py` and the rule tests.', '']
        for tb in tables: md += fmt(tb, refs, tc) + ['']
        open(os.path.join(ROOT, 'docs/pooling/IMPACT_MAP.md'), 'w').write('\n'.join(md))
        print('wrote docs/pooling/IMPACT_MAP.md')
